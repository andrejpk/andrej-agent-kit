"""Generate GitHub Copilot custom agents from the Claude plugin agents.

The Claude agent files in plugins/*/agents/*.md stay the source of truth. This
writes Copilot-format copies to plugins/*/copilot/agents/<name>.agent.md.

    python scripts/sync_copilot_agents.py          # rewrite
    python scripts/sync_copilot_agents.py --check  # exit 1 if out of date
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Claude tool name -> Copilot tool alias
TOOL_MAP = {
    "Read": "read",
    "Grep": "search",
    "Glob": "search",
    "Bash": "execute",
    "Edit": "edit",
    "Write": "edit",
}

FRONT_MATTER = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n(.*)\Z", re.DOTALL)


def convert(text: str) -> str:
    match = FRONT_MATTER.match(text)
    if not match:
        raise ValueError("agent file has no front matter")
    fields: dict[str, str] = {}
    for line in match.group(1).splitlines():
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip()
    tools: list[str] = []
    for name in fields.get("tools", "").split(","):
        name = name.strip()
        if not name:
            continue
        alias = TOOL_MAP.get(name)
        if alias is None:
            raise ValueError(f"no Copilot tool mapping for {name!r}")
        if alias not in tools:
            tools.append(alias)
    description = fields["description"].replace("'", "''")
    header = [
        "---",
        f"name: {fields['name']}",
        f"description: '{description}'",
        "tools: [" + ", ".join(f"'{t}'" for t in tools) + "]",
        "---",
        "",
        "<!-- Generated by scripts/sync_copilot_agents.py from the Claude agent. Do not edit. -->",
        "",
    ]
    return "\n".join(header) + match.group(2).replace("\r\n", "\n")


def targets() -> list[tuple[Path, Path]]:
    pairs = []
    for source in sorted((ROOT / "plugins").glob("*/agents/*.md")):
        plugin = source.parent.parent
        pairs.append((source, plugin / "copilot" / "agents" / f"{source.stem}.agent.md"))
    return pairs


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for source, target in targets():
        expected = convert(source.read_text(encoding="utf-8"))
        current = target.read_text(encoding="utf-8") if target.exists() else None
        if current == expected:
            continue
        stale.append(target)
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected, encoding="utf-8", newline="\n")
    for target in stale:
        print(("out of date: " if check else "wrote: ") + str(target.relative_to(ROOT)))
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
